"""Geräte-Interface. Echtes Gerät ↔ Fake-Gerät ist ein Config-Eintrag."""

from __future__ import annotations

from typing import Protocol, runtime_checkable

from adbbot.core.types import Frame, Point, Size

# Häufige Android-Keycodes (vollständige Liste: android.view.KeyEvent)
KEY_HOME = 3
KEY_BACK = 4
KEY_POWER = 26
KEY_ENTER = 66
KEY_DEL = 67
KEY_MENU = 82
KEY_ESCAPE = 111
KEY_APP_SWITCH = 187


@runtime_checkable
class DeviceProtocol(Protocol):
    """Alle Methoden werfen bei Kommunikationsproblemen `DeviceError`."""

    @property
    def serial(self) -> str: ...

    def connect(self) -> None: ...
    def disconnect(self) -> None: ...
    def is_connected(self) -> bool: ...
    def screen_size(self) -> Size: ...
    def screenshot(self) -> Frame: ...
    def tap(self, p: Point) -> None: ...
    def swipe(self, a: Point, b: Point, duration_ms: int) -> None: ...
    def long_press(self, p: Point, duration_ms: int) -> None: ...
    def key(self, keycode: int) -> None: ...
    def input_text(self, text: str) -> None: ...
    def start_app(self, package: str, activity: str | None = None) -> None: ...
    def stop_app(self, package: str) -> None: ...
    def current_app(self) -> str | None: ...
    def current_activity(self) -> str | None: ...
    def bring_to_front(self, package: str) -> None: ...
    def dump_ui(self) -> str | None: ...
